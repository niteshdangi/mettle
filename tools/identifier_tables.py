#!/usr/bin/env python3
"""Generate the compiler's pinned Unicode 16.0.0 identifier tables."""

import argparse
import hashlib
from pathlib import Path

from unicode_tables import format_array, property_ranges

INPUTS = {
    "DerivedCoreProperties.txt": "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd",
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "DerivedNormalizationProps.txt": "4d4c03892dea9146d674b686e495df2d55a28d071ac474041d73518f887abddc",
}


def generate(directory):
    files = {}
    for name, digest in INPUTS.items():
        data = (directory / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"{name}: input differs from Unicode 16.0.0")
        files[name] = data.decode("utf-8")
    properties = property_ranges(files["DerivedCoreProperties.txt"], ("XID_Start", "XID_Continue"))
    excluded_ranges = property_ranges(files["DerivedNormalizationProps.txt"], ("Full_Composition_Exclusion",))
    excluded = {value for start, end in excluded_ranges["Full_Composition_Exclusion"]
                for value in range(start, end + 1)}
    combining, decompositions, compositions = [], {}, []
    for line in files["UnicodeData.txt"].splitlines():
        fields = line.split(";")
        scalar, category = int(fields[0], 16), int(fields[3])
        if category:
            if combining and combining[-1][1] + 1 == scalar and combining[-1][2] == category:
                combining[-1] = (combining[-1][0], scalar, category)
            else:
                combining.append((scalar, scalar, category))
        decomposition = fields[5]
        if decomposition and not decomposition.startswith("<"):
            values = tuple(int(value, 16) for value in decomposition.split())
            decompositions[scalar] = values
            if len(values) == 2 and scalar not in excluded:
                compositions.append((*values, scalar))

    def expand(scalar):
        return [part for value in decompositions[scalar]
                for part in (expand(value) if value in decompositions else [value])]

    mappings, scalars = [], []
    for scalar in sorted(decompositions):
        expanded = expand(scalar)
        mappings.extend((scalar, len(scalars), len(expanded)))
        scalars.extend(expanded)
    tables = {
        "XID_START": [value for pair in properties["XID_Start"] for value in pair],
        "XID_CONTINUE": [value for pair in properties["XID_Continue"] for value in pair],
        "COMBINING": [value for row in combining for value in row],
        "DECOMPOSITIONS": mappings,
        "DECOMPOSED": scalars,
        "COMPOSITIONS": [value for row in sorted(compositions) for value in row],
    }
    return "// Generated by tools/identifier_tables.py from Unicode 16.0.0 UCD.\n\n" + "\n\n".join(
        format_array(name, values).replace("static ", "pub parent static ", 1)
        for name, values in tables.items()) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd_dir", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd_dir), encoding="utf-8", newline="\n")
